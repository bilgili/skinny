def test_every_compute_entry_is_registered_or_excluded():
    """Scenario: a new pass without registration fails the build."""
    registered = {p.entry_key for p in PASSES}
    excluded = {x.key for x in rec.RECORDABLE_EXCLUSIONS}
    missing = sorted(rec.compute_entry_points() - registered - excluded)
    assert missing == [], (
        "these compute entry points are neither registered in "
        "RECORDABLE_PASSES nor excluded with a reason in "
        f"RECORDABLE_EXCLUSIONS: {missing}")


def test_no_exclusion_names_a_pass_that_no_longer_exists():
    """Scenario: an exclusion states its reason — and none is stale.

    A stale exclusion silently re-admits the gap it was meant to bound.
    """
    stale = sorted({x.key for x in rec.RECORDABLE_EXCLUSIONS}
                   - rec.compute_entry_points())
    assert stale == []
    for exclusion in rec.RECORDABLE_EXCLUSIONS:
        assert len(exclusion.reason) > 20, exclusion


def test_no_entry_point_is_both_registered_and_excluded():
    registered = {p.entry_key for p in PASSES}
    both = registered & {x.key for x in rec.RECORDABLE_EXCLUSIONS}
    assert both == set()


def test_entry_points_are_keyed_by_module_as_well_as_name():
    """Multiple modules declare `computeMain` (foundation_trivial, tool_probe,
    and the denoise passes when present); a name-keyed map would collapse them
    and report an unregistered pass as covered. Keying by (module, name) keeps
    each distinct."""
    same_name = [key for key in rec.compute_entry_points()
                 if key[1] == "computeMain"]
    assert len(same_name) >= 2


def test_an_entry_point_with_a_brace_in_a_comment_is_still_found(tmp_path):
    """`compute_entry_points` strips comments over the whole file, so a `{`
    inside a `//` comment between `[shader("compute")]` and `void` must not hide
    the entry from the scan (codex review)."""
    (tmp_path / "m.slang").write_text(
        '[shader("compute")] // writes into {tile}\n'
        "[numthreads(1,1,1)]\n"
        "void kern(uint3 t : SV_DispatchThreadID) {}\n")
    assert ("m", "kern") in rec.compute_entry_points(tmp_path)


def test_entry_scan_excludes_generated_untracked_shaders(tmp_path):
    """The scan counts only SOURCE (git-tracked) shaders, not the renderer's
    per-scene generated output.

    The renderer emits `generated_materials.slang` and per-material
    `wavefront/shade_<Material>.slang` modules — each with a `[shader("compute")]`
    entry — into the tree at run time. They are never `git add`ed, so on any
    checkout that has rendered, a plain rglob would surface them and fail the
    registry meta-test with entries that must not be registered. A git fixture
    proves the tracked source entry is found and the untracked generated one is
    not."""
    import subprocess

    def git(*args):
        subprocess.run(["git", "-C", str(tmp_path), *args],
                       check=True, capture_output=True)

    git("init", "-q")
    (tmp_path / "wavefront").mkdir()
    (tmp_path / "src_pass.slang").write_text(
        '[shader("compute")] [numthreads(1,1,1)]\n'
        "void sourceKern(uint3 t : SV_DispatchThreadID) {}\n")
    git("add", "src_pass.slang")
    # Emitted at run time, never committed — a real compute entry.
    (tmp_path / "wavefront" / "shade_Marble.slang").write_text(
        '[shader("compute")] [numthreads(1,1,1)]\n'
        "void shadeSurface_Marble(uint3 t : SV_DispatchThreadID) {}\n")

    found = rec.compute_entry_points(tmp_path)
    assert ("src_pass", "sourceKern") in found
    assert ("wavefront.shade_Marble", "shadeSurface_Marble") not in found


def test_entry_scan_survives_block_comments_and_whitespace(tmp_path):
    """Codex review, finding 4: the entry scan strips BOTH comment forms and
    tolerates Slang's whitespace, so it neither misses a real entry nor invents
    a phantom one.

    Three cases, all valid Slang: a `{` inside a `/* */` block comment between
    the attribute and `void` (was hidden); `shader ("compute")` with spaces (was
    missed); and an entry-shaped string sitting inside a block comment (was
    reported as real).
    """
    (tmp_path / "block.slang").write_text(
        '[shader("compute")] /* fills { the tile */\n'
        "[numthreads(1,1,1)]\n"
        "void blockKern(uint3 t : SV_DispatchThreadID) {}\n")
    (tmp_path / "space.slang").write_text(
        '[ shader ( "compute" ) ]\n'
        "[numthreads(1,1,1)]\n"
        "void spaceKern(uint3 t : SV_DispatchThreadID) {}\n")
    (tmp_path / "fake.slang").write_text(
        "/* not real:\n"
        '   [shader("compute")] void ghost(uint3 t : SV_DispatchThreadID) {}\n'
        "*/\n"
        "float helper() { return 1.0; }\n")
    found = rec.compute_entry_points(tmp_path)
    assert ("block", "blockKern") in found
    assert ("space", "spaceKern") in found
    assert ("fake", "ghost") not in found


def test_entry_scan_does_not_join_two_line_comments_into_a_block(tmp_path):
    """Codex round-5 regression: stripping block comments before line comments
    let a `/*` in one `//` line and a `*/` in a later `//` line be read as a
    real block delimiter, erasing the entry between them. The single-pass lexer
    knows `/*` inside a `//` line is just text, so the entry survives."""
    (tmp_path / "m.slang").write_text(
        "// opens a fake block /*\n"
        '[shader("compute")]\n'
        "[numthreads(1,1,1)]\n"
        "void survivor(uint3 t : SV_DispatchThreadID) {}\n"
        "// closes it */\n")
    assert ("m", "survivor") in rec.compute_entry_points(tmp_path)


def test_entry_scan_treats_an_inline_block_comment_as_a_separator(tmp_path):
    """Codex round-6: a removed block comment must become a space, not nothing —
    an inline `/* */` is a legal token separator, so `void/* */name` lexes to
    `void name`. Deleting it outright yields `voidname` and the entry vanishes
    before `_ENTRY_RE`."""
    (tmp_path / "m.slang").write_text(
        '[shader("compute")] [numthreads(1,1,1)]\n'
        "void/* legal separator */sep(uint3 t : SV_DispatchThreadID) {}\n")
    assert ("m", "sep") in rec.compute_entry_points(tmp_path)


def test_entry_module_key_is_platform_neutral(tmp_path):
    """Codex round-6: the module key is `".".join(parts)`, not
    `.replace("/", ".")`, so a nested entry keys the same on every OS and matches
    its dotted registry/exclusion entry."""
    nested = tmp_path / "wavefront"
    nested.mkdir()
    (nested / "wavefront_path.slang").write_text(
        '[shader("compute")] [numthreads(1,1,1)]\n'
        "void wfKern(uint3 t : SV_DispatchThreadID) {}\n")
    assert ("wavefront.wavefront_path", "wfKern") in rec.compute_entry_points(
        tmp_path)


# ── the gate is provably able to fail (D4) ───────────────────────────────


def test_the_negative_control_reports_the_omitted_global():
    """Scenario: the negative control is reported.

    A fixture pass identical to the megakernel except that its bind map drops
    exactly one global the compiler reflects. Routed through :func:`run_pass` —
    the same call the real gate uses.
    """
    omitted = "sphereLights"
    megakernel = next(p for p in PASSES if p.name == "megakernel")

    def sabotaged(ctx):
        binds, bindless = megakernel.binds(ctx)
        assert omitted in binds, "the fixture must omit a genuinely bound name"
        return ({k: v for k, v in binds.items() if k != omitted}, bindless)

    control = rec.RecordablePass(
        name="megakernel", entry_module=megakernel.entry_module,
        entry_point=megakernel.entry_point, key=megakernel.key,
        binds=sabotaged,
    )
    assert run_pass(control) == [(megakernel.entry_point, omitted)]
    # The real pass, through the same call, still reports nothing — so the
    # control isolates the omission rather than a broken harness.
    assert run_pass(megakernel) == []


def test_a_present_but_empty_binding_still_counts_as_omitted():
    """A key bound to `None` is unbound, not bound (the rule
    `tests/test_gpu_backend.py::test_recorder_treats_a_none_resource_as_unbound`
    pins). Asserted here too, because it is what stops a skipped bind from
    reading as a satisfied one for a real pass."""
    omitted = "sphereLights"
    megakernel = next(p for p in PASSES if p.name == "megakernel")

    def nulled(ctx):
        binds, bindless = megakernel.binds(ctx)
        return ({**binds, omitted: None}, bindless)

    control = rec.RecordablePass(
        name="megakernel", entry_module=megakernel.entry_module,
        entry_point=megakernel.entry_point, key=megakernel.key, binds=nulled,
    )
    assert run_pass(control) == [(megakernel.entry_point, omitted)]


# ── hostless (task 6.2) ──────────────────────────────────────────────────

GPU_PACKAGES = ("vulkan", "slangpy")

_BLOCKER = """
import sys

class _Blocked:
    def find_module(self, name, path=None):
        return self.find_spec(name, path)

    def find_spec(self, name, path=None, target=None):
        if name.split(".")[0] in {gpu!r}:
            raise ImportError("blocked by the hostless coverage gate: " + name)
        return None

sys.meta_path.insert(0, _Blocked())
"""


def test_the_gate_runs_with_no_gpu_package_importable():
    """Scenario: coverage runs with no GPU.

    The whole point of a recording adapter is that binding coverage stops
    needing a dual-device host, so the gate is proved to complete in a process
    where neither backend package can even be imported. The golden is read from
    disk, so no compiler runs here either.
    """
    code = _BLOCKER.format(gpu=set(GPU_PACKAGES)) + textwrap.dedent(f"""
        import json, sys
        from pathlib import Path

        from skinny import recording_compute as rec

        golden = json.loads(Path({str(GOLDEN_PATH)!r}).read_text())
        for p in rec.RECORDABLE_PASSES:
            ctx = rec.RecordingContext()
            pipe = rec.ComputePipeline(ctx, rec.shader_dir(), p.entry_module,
                                       p.entry_point)
            pipe.reflect_globals(golden[p.name]["globals"])
            binds, bindless = p.binds(ctx)
            pipe.dispatch(8, 8, uniform_blob=b"", binds=binds,
                          bindless=bindless)
            missing = ctx.recorder.missing_bindings()
            assert missing == [], (p.name, missing)
        for gpu in ("vulkan", "slangpy"):
            assert gpu not in sys.modules, gpu
        print("OK", len(rec.RECORDABLE_PASSES))
    """)
    result = subprocess.run([sys.executable, "-c", code],
                            capture_output=True, text=True, check=False)
    assert result.returncode == 0, result.stderr
    assert result.stdout.startswith("OK "), result.stdout
