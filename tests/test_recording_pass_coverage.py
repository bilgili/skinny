"""Binding coverage for real passes — change ``recording-adapter-live-bindings``.

``Recorder.missing_bindings()`` names every shader global a dispatch left
unbound. On Metal an unbound global is a silent zero rather than a crash, so
catching one before the GPU is worth a lot — but only if both sides of the
comparison are real. Until this change every caller wrote both::

    pipe.reflect_globals({"outputBuffer", "sceneBuffer"})   # hand-written
    pipe.dispatch(8, 8, binds={"outputBuffer": buf})        # hand-written

which asserts that two literals the same author wrote disagree where that
author expected. Those scenarios still live in ``tests/test_gpu_backend.py``,
relabelled: they test the RECORDER, not any pass.

Here the two sides are both real, and neither is written in this file:

* The **declared** side comes from the compiler. ``slangc``'s reflection of each
  pass is generated offline into
  ``tests/fixtures/recording_pass_globals.json`` by
  ``tests/fixtures/gen_recording_pass_globals.py`` and trusted here exactly as
  the checked-in ``.spv`` is trusted. A hand parser could not tell a file-scope
  resource global from a function parameter of resource type without full scope
  tracking, and codex pre-merge review kept finding valid Slang spellings it
  under-reported — the exact fail-open the gate exists to prevent. The compiler
  does not miss a declaration, so that failure class is gone.
* The **bound** side comes from ``SceneResourceSet.metal_binds`` — the single
  builder the renderer's ``_build_metal_binds`` delegates to.

The negative control proves the comparison can still fail.

Hostless: plain ``pytest`` runs it (the golden is read, not regenerated), and
:func:`test_the_gate_runs_with_no_gpu_package_importable` proves it needs
neither backend.
"""

from __future__ import annotations

import json
import subprocess
import sys
import textwrap
from pathlib import Path

import pytest

from skinny import recording_compute as rec
from skinny.gpu_resources import DECLARATIONS

GOLDEN_PATH = (Path(__file__).parent / "fixtures"
               / "recording_pass_globals.json")
GOLDEN = json.loads(GOLDEN_PATH.read_text())

PASSES = rec.RECORDABLE_PASSES
IDS = [p.name for p in PASSES]


def _default_layout(decl) -> bool:
    """Is this declaration in the plain RGB, no-denoiser layout the megakernel
    reflects? Uses `ResourceDecl.in_default_layout` where it exists (a base that
    carries the denoise/aov axes) and falls back to `not spectral` otherwise, so
    the megakernel gate reads the same on this branch and on one with denoise."""
    return getattr(decl, "in_default_layout", not decl.spectral)


def declared_globals(pass_) -> set[str]:
    """The compiler-reflected globals for a pass, from the checked-in golden.

    Trusted, not re-derived: the golden is regenerated by
    ``gen_recording_pass_globals.py`` and diffed against reality by the
    gpu-marked freshness test below.
    """
    return set(GOLDEN[pass_.name]["globals"])


# ── the gate ─────────────────────────────────────────────────────────────


def run_pass(pass_, declared=None) -> list[tuple[str, str]]:
    """Drive one registered pass through the recorder and report what it left
    unbound.

    The ONE call the coverage gate and its negative control both use: a
    parallel hand-built path would prove only that the parallel path works.
    ``declared`` overrides the golden set only for the negative control.
    """
    ctx = rec.RecordingContext()
    pipe = rec.ComputePipeline(ctx, rec.shader_dir(), pass_.entry_module,
                               pass_.entry_point)
    pipe.reflect_globals(declared_globals(pass_) if declared is None else declared)
    binds, bindless = pass_.binds(ctx)
    # `uniform_blob` binds `fc`, `bindless` binds the pool under its own global
    # — the same two non-`binds` channels the real dispatch uses.
    pipe.dispatch(8, 8, uniform_blob=b"", binds=binds, bindless=bindless)
    return ctx.recorder.missing_bindings()


@pytest.mark.parametrize("pass_", PASSES, ids=IDS)
def test_registered_pass_binds_every_declared_global(pass_):
    """Scenario: a fully bound pass reports nothing — every global the compiler
    reflects for the pass is supplied by the host's real bind map."""
    assert run_pass(pass_) == []


@pytest.mark.parametrize("pass_", PASSES, ids=IDS)
def test_declared_globals_come_from_the_compiler_not_the_test(pass_):
    """Scenario: globals come from the shader, not the test.

    The golden entry names the pass's own entry module/point, and its globals
    are non-empty — so no literal set written in this file is standing in for
    the compiler's reflection.
    """
    entry = GOLDEN[pass_.name]
    assert entry["entry_module"] == pass_.entry_module
    assert entry["entry_point"] == pass_.entry_point
    assert entry["globals"], f"{pass_.name} reflected nothing — golden is stale"


def test_the_golden_covers_exactly_the_registry():
    """The golden and the registry name the same passes — a pass added without
    regenerating the golden (or a stale golden entry) fails here rather than
    silently skipping coverage."""
    assert set(GOLDEN) == {p.name for p in PASSES}


def test_the_bind_map_is_the_hosts_own_builder():
    """The bound side is not written here either: it is whatever
    ``SceneResourceSet.metal_binds`` produces, which is the single builder the
    renderer's ``_build_metal_binds`` delegates to."""
    import inspect

    from skinny import gpu_resources

    binds, _ = rec.scene_binds(rec.RecordingContext())
    assert set(binds) >= {d.metal for d in DECLARATIONS
                          if d.metal and _default_layout(d)}
    body = inspect.getsource(gpu_resources.SceneResourceSet.metal_binds)
    assert "commonSampler" in body, (
        "the renderer-owned globals must be added inside metal_binds, or the "
        "gate sees a different map from the one a frame binds")


# ── the golden agrees with an independently maintained table (D5) ────────


def test_golden_agrees_with_the_gpu_resource_inventory():
    """Scenario: the compiler reflection agrees with an independently maintained
    table.

    ``gpu_resources.DECLARATIONS`` records each resource's Vulkan binding number
    and Metal global name for a completely different reason (allocating and
    binding them). The megakernel golden must name exactly the default-layout
    inventory resources it reaches — a fourth going missing, or an inventory
    name the golden lacks, fails here.
    """
    megakernel = declared_globals(next(p for p in PASSES if p.name == "megakernel"))
    inventory = {d.metal for d in DECLARATIONS if _default_layout(d) and d.metal}
    # The megakernel strips the neural proposal at build, so the three neural
    # buffers are the only default-layout inventory resources it does not
    # declare (Compatibility matrix: neural is wavefront-only). That exclusion
    # is the independently maintained leg.
    MEGAKERNEL_ABSENT = {"neuralWeights", "neuralBiases", "neuralLayers"}
    # EQUALITY, not containment (codex review): the golden's inventory-named
    # subset must be EXACTLY `inventory − MEGAKERNEL_ABSENT`. Containment
    # accepted a golden that carried an extra inventory name it should not (e.g.
    # a stray `neuralWeights`) — the drift D5 exists to catch. Restrict to
    # inventory names first, because the golden also carries `fc` /
    # `flatMaterialTextures` / `commonSampler`, which the inventory does not name
    # (pinned separately below).
    golden_inventory = megakernel & inventory
    assert golden_inventory == inventory - MEGAKERNEL_ABSENT, (
        "megakernel golden disagrees with the resource inventory: "
        f"missing {sorted((inventory - MEGAKERNEL_ABSENT) - golden_inventory)}, "
        f"unexpected {sorted(golden_inventory - (inventory - MEGAKERNEL_ABSENT))}"
        " — regenerate the golden or fix the inventory")
    # …and the absent set is genuinely absent, not merely un-required: a golden
    # that started declaring a neural buffer must fail, which pure equality above
    # would already catch, but this states the intent directly.
    assert not (megakernel & MEGAKERNEL_ABSENT), (
        f"golden declares a resource the megakernel strips at build: "
        f"{sorted(megakernel & MEGAKERNEL_ABSENT)}")


def test_the_globals_without_an_inventory_entry_are_the_recorded_three():
    """The three megakernel globals ``DECLARATIONS`` deliberately does not name:
    the uniform block (bound as a blob, not a resource), the bindless pool
    (passed as the separate ``bindless`` argument) and the renderer-owned shared
    sampler. Pinned so a fourth cannot appear unnoticed."""
    megakernel = declared_globals(next(p for p in PASSES if p.name == "megakernel"))
    named = {d.metal for d in DECLARATIONS if d.metal}
    samplers = {d.metal + "Sampler" for d in DECLARATIONS if d.metal_sampler}
    unnamed = megakernel - named - samplers
    assert unnamed == {"fc", "flatMaterialTextures", "commonSampler"}


